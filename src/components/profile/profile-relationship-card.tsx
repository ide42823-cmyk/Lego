/** Cards are a fixed width so a row of them lines up with the reference's grid. */
const CARD_WIDTH = 104;

/** Our own winged heart and cloud band, generated by `tools/build-art.mjs`. */
const WING_HEART = artSource('wingHeart');
const CLOUDS = artSource('clouds');

export interface CouplePanelProps {
  /**
   * The couple record, or `null` when this member has none yet. The card renders
   * either way: with no couple the second slot is the invitation, which is what
   * the reference shows a single member.
   */
  record?: RelationshipRecord;
  ownerId: string;
  ownerName: string;
  ownerAvatarUrl?: string;
  /** The owner's own frame, so both sides of the pair are dressed alike. */
  ownerFrame?: AvatarFrameKey;
  /** Opens the relationship's detail; only reachable when there is a record. */
  onPress: (record: RelationshipRecord) => void;
  onInvite: () => void;
}

/**
 * The couple panel (reference screens 018, 021–023).
 *
 * The duration is the relationship's own fact, so it is shown under the heart
 * between the pair rather than as a badge on either member.
 */
export function CouplePanel({
  record,
  ownerId,
  ownerName,
  ownerAvatarUrl,
  ownerFrame,
  onPress,
  onInvite,
}: CouplePanelProps) {
  const tints = useTints();
  const palette = tints.couple;

  const side = (
    id: string,
    name: string,
    uri: string | undefined,
    frame: AvatarFrameKey | undefined,
    withHeart: boolean,
  ): ReactElement => (
    <View style={styles.coupleSide}>
      <FramedAvatar id={id} name={name} uri={uri} frame={frame} size={58} />
      <View style={styles.coupleNameRow}>
        {withHeart ? (
          <Icon name="greeting" size={11} color={palette.text} fill={palette.text} />
        ) : null}
        <ThemedText
          type="small"
          numberOfLines={1}
          style={[styles.coupleName, { color: palette.text }]}
        >
          {name}
        </ThemedText>
      </View>
    </View>
  );

  const card = (
    <View style={styles.coupleCard}>
      <CoupleBackdrop />
      <View style={styles.coupleRow}>
        {side(ownerId, ownerName, ownerAvatarUrl, ownerFrame, true)}

        <View style={styles.emblem}>
          <Image
            source={WING_HEART}
            style={styles.wingHeart}
            contentFit="contain"
            {...DECORATIVE_IMAGE}
          />
          {record ? (
            <View style={styles.daysPill}>
              <ThemedText type="small" style={[styles.daysLabel, { color: palette.muted }]}>
                {`Lv.${record.level} · ${record.days} days`}
              </ThemedText>
            </View>
          ) : null}
        </View>

        {record ? (
          side(record.peerId, record.peerName, record.peerAvatarUrl, record.peerFrame, false)
        ) : (
          <View style={styles.coupleSide}>
            <Pressable
              accessibilityRole="button"
              accessibilityLabel={`Invite a member to be ${ownerName}'s couple`}
              onPress={onInvite}
              style={({ pressed }) => [styles.inviteCircle, pressed && styles.pressed]}
            >
              <Icon name="invite" size={24} strokeWidth={2} color={palette.text} />
            </Pressable>
            <ThemedText type="small" style={[styles.coupleName, { color: palette.text }]}>
              Invite
            </ThemedText>
          </View>
        )}
      </View>
    </View>
  );

  if (!record) {
    return card;
  }

  return (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={`Couple level ${record.level} with ${record.peerName}, ${record.days} days`}
      onPress={() => onPress(record)}
      style={({ pressed }) => pressed && styles.pressed}
    >
      {card}
    </Pressable>
  );
}

/**
 * The rose wash and cloud band behind the couple. Drawn rather than tinted with
 * a flat fill so the card reads as a surface of its own, the way the reference's
 * does, in both schemes.
 */
function CoupleBackdrop() {
  const tints = useTints();
  const palette = tints.couple;
  const isDark = useColorScheme() === 'dark';

  return (
    <View style={styles.backdrop} pointerEvents="none" accessible={false}>
      <Svg style={StyleSheet.absoluteFill}>
        <Defs>
          <LinearGradient id="couple-wash" x1="0" y1="0" x2="1" y2="1">
            <Stop offset="0" stopColor={palette.from} />
            <Stop offset="1" stopColor={palette.to} />
          </LinearGradient>
        </Defs>
        <Rect x="0" y="0" width="100%" height="100%" fill="url(#couple-wash)" />
      </Svg>
      {/*
        The clouds stay in the upper band: the names sit at the card's foot, and a
        white cloud under white type erases it. They are also weaker in the dark
        scheme, where a full-strength white band would flatten the deep rose.
      */}
      <Image
        source={CLOUDS}
        style={[styles.clouds, { opacity: isDark ? 0.22 : 0.6 }]}
        contentFit="fill"
        {...DECORATIVE_IMAGE}
      />
      {/*
        A floor shade the names can be read against. It is a gradient, not a
        plate: it deepens the card's foot the way the reference's does.
      */}
      <Svg style={StyleSheet.absoluteFill}>
        <Defs>
          <LinearGradient id="couple-floor" x1="0" y1="0" x2="0" y2="1">
            <Stop offset="0.5" stopColor="#5E0A2C" stopOpacity="0" />
            <Stop offset="1" stopColor="#5E0A2C" stopOpacity={isDark ? 0.4 : 0.6} />
          </LinearGradient>
        </Defs>
        <Rect x="0" y="0" width="100%" height="100%" fill="url(#couple-floor)" />
      </Svg>
    </View>
  );
}

export interface FriendCardProps {
  record: RelationshipRecord;
  onPress: (record: RelationshipRecord) => void;
}

/** One friend relationship tile. */
export function FriendCard({ record, onPress }: FriendCardProps) {
  const theme = useTheme();
  const tints = useTints();
  const colors = tints.chip.chat;

  return (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={`Friend level ${record.level} with ${record.peerName}, ${record.days} days`}
      onPress={() => onPress(record)}
      style={({ pressed }) => [
        styles.friendCard,
        { backgroundColor: colors.background, borderColor: colors.text },
        pressed && { opacity: 0.8 },
      ]}
    >
      <View style={styles.friendAvatar}>
        <FramedAvatar
          id={record.peerId}
          name={record.peerName}
          uri={record.peerAvatarUrl}
          frame={record.peerFrame}
          size={48}
        />
        <View
          style={[
            styles.friendBadge,
            { backgroundColor: colors.text, borderColor: theme.background },
          ]}
        >
          <Icon name="rank" size={11} strokeWidth={2.4} color="#FFFFFF" />
        </View>
      </View>

      <ThemedText
        type="small"
        numberOfLines={1}
        style={[styles.friendName, { color: colors.text }]}
      >
        {record.peerName}
      </ThemedText>

      <View style={[styles.friendLevel, { borderColor: colors.text }]}>
        <ThemedText type="small" style={[styles.levelLabel, { color: colors.text }]}>
          {`Friend Lv.${record.level}`}
        </ThemedText>
      </View>

      <Divider />

      <ThemedText type="small" style={[styles.levelLabel, { color: colors.text }]}>
        {`${record.days} days`}
      </ThemedText>
    </Pressable>
  );
}

